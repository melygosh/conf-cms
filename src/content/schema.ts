import { z } from 'astro/zod';

export type Lang = 'uk' | 'en';
export const LANGS: Lang[] = ['uk', 'en'];

/** A value that must be present in both languages. */
export const localized = <T extends z.ZodType>(t: T) => z.object({ uk: t, en: t }).strict();

// YAML parses an unquoted `2026-01-25` into a Date at UTC midnight; a quoted one stays a string.
// Anything else ("January 25", "2027/01/25", 20270125, 2026-02-30) is rejected rather than guessed.
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
const DATE_HINT = 'Use a YYYY-MM-DD date, e.g. 2027-01-25';

const isoDate = z.union([z.date(), z.string()]).transform((value, ctx) => {
  const date = typeof value === 'string' ? new Date(`${value}T00:00:00Z`) : value;
  const valid =
    !Number.isNaN(date.getTime()) &&
    date.getUTCHours() === 0 &&
    date.getUTCMinutes() === 0 &&
    (typeof value !== 'string' || (ISO_DATE.test(value) && date.toISOString().slice(0, 10) === value));
  if (!valid) {
    ctx.addIssue({ code: 'custom', message: DATE_HINT });
    return z.NEVER;
  }
  return date;
});
const url = z.url();

// Prices come from each language's own call for papers (amounts and currency differ), so each language has its own list.
const costLang = z
  .object({
    items: z
      .array(
        z.object({ label: z.string(), amount: z.string(), unit: z.string().optional(), note: z.string().optional() }).strict(),
      )
      .min(1),
    payment: z.string(),
  })
  .strict();

export const conferenceSchema = z
  .object({
    year: z.number().int(),
    edition: z.number().int().positive(),
    title: localized(z.string()),
    dates: z.object({ start: isoDate, end: isoDate }).strict(),
    /** "We invite you…", verbatim from the call for papers. */
    invitation: localized(z.string()),
    venue: z
      .object({
        place: localized(z.string()),
        description: localized(z.string()),
        name: localized(z.string()),
        address: localized(z.string()),
        url: localized(url),
        director: localized(z.string()).optional(),
        format: localized(z.string()),
        mapEmbedUrl: url,
        mapLink: url,
      })
      .strict(),
    // Without infoLetter the site links the letter generated by `npm run letter`.
    links: z.object({ registration: localized(url), infoLetter: localized(url).optional() }).strict(),
    // Shown as cards linking to the organizer's site; logo is a path under public/ (optional until a file exists).
    organizers: z
      .array(
        z.object({ name: localized(z.string()), href: url, logo: z.string().startsWith('/').optional() }).strict(),
      )
      .min(1),
    aim: localized(z.string()),
    sections: z.array(
      z
        .object({
          name: localized(z.string()),
          items: localized(z.array(z.string())).optional(),
          text: localized(z.string()).optional(),
        })
        .strict(),
    ),
    languages: localized(z.string()),
    publication: z
      .object({
        summary: localized(z.string()),
        rules: localized(z.string()),
        formatting: localized(z.string()),
        articles: z
          .object({
            journalUrl: url,
            // A language whose call for papers gives no template link has none.
            templateUrl: z.object({ uk: url, en: url }).partial().strict(),
            badges: localized(z.array(z.string()).min(1)),
            review: localized(z.string()),
            requirements: localized(z.string()),
          })
          .strict(),
      })
      .strict(),
    /** What goes to the Program Committee and how (the form, or e-mail). */
    submission: localized(z.array(z.object({ title: z.string(), text: z.string() }).strict()).min(1)),
    deadlines: z.array(
      z
        .object({
          date: isoDate,
          // A deadline only one language's call for papers has (e.g. the fee, free for foreign participants)
          // is marked `only`, and only that language's title is required.
          title: z.object({ uk: z.string(), en: z.string() }).partial().strict(),
          only: z.enum(['uk', 'en']).optional(),
          group: z.enum(['participation', 'papers']).default('participation'),
          countdown: z.boolean().default(false),
          /** Registration (and the form's buttons) closes after this deadline. */
          registration: z.boolean().default(false),
        })
        .strict(),
    ),
    cost: z.object({ uk: costLang, en: costLang }).strict(),
    authors: z.array(z.object({ title: localized(z.string()), body: localized(z.string()) }).strict()),
    committees: localized(z.string()),
  })
  .strict()
  .superRefine((c, ctx) => {
    if (c.dates.start.getUTCFullYear() !== c.year) {
      ctx.addIssue({ code: 'custom', path: ['dates', 'start'], message: `Conference start is not in year ${c.year}` });
    }
    if (c.dates.end < c.dates.start) {
      ctx.addIssue({ code: 'custom', path: ['dates', 'end'], message: 'Conference ends before it starts' });
    }
    c.deadlines.forEach((d, i) => {
      for (const lang of LANGS) {
        if ((!d.only || d.only === lang) && !d.title[lang]) {
          ctx.addIssue({ code: 'custom', path: ['deadlines', i, 'title', lang], message: `Missing ${lang} title` });
        }
      }
      if (d.registration && c.deadlines.findIndex((x) => x.registration) !== i) {
        ctx.addIssue({ code: 'custom', path: ['deadlines', i, 'registration'], message: 'Only one deadline can close registration' });
      }
    });
  });

export const archiveSchema = z
  .object({
    year: z.number().int(),
    /** The book of abstracts in the KhPI repository. */
    proceedings: url.optional(),
    photos: url.optional(),
    presentations: z
      .array(z.object({ author: z.string(), title: z.string(), href: url }).strict())
      .default([]),
  })
  .strict();

export const siteSchema = z
  .object({
    contacts: localized(z.string()),
    khpiMapEmbedUrl: url,
    partners: z.array(z.object({ name: z.string(), href: url, image: z.string() }).strict()),
  })
  .strict();

export type Conference = z.infer<typeof conferenceSchema>;
export type ArchiveYear = z.infer<typeof archiveSchema>;
export type Site = z.infer<typeof siteSchema>;
